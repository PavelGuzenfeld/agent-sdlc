"""Intent: #112 (decision 38 of #103) — every core concept word not itself a
function word, symbol or convention name appears in at least 2 of the 6
public repos this ticket names, checked against the committed evidence
table `tests/fixtures/vocabulary_core_mining_table.toml` (regenerated by
`tests/mine_vocabulary_core.py`). A concept below that count is an
explicit, named exception, never a silent gap."""

import tomllib
from pathlib import Path

import pytest

from mutation_gate import no_leaks, vocabulary, vocabulary_wordnet
from mutation_gate.repo import GateError

REPO_ROOT = Path(__file__).resolve().parents[2]
MINING_TABLE = REPO_ROOT / "tests" / "fixtures" / "vocabulary_core_mining_table.toml"
CORE_PATH = REPO_ROOT / "mutation_gate" / "vocabulary_core.toml"

EXCEPTIONS = {
    "touch": "test_circle_touching_corner_at_zero_heading_overlaps in "
             "test_mutation_gate_vocabulary_molds.py pins the whole test-name example",
    "circle": "same test-name example as touch",
    "corner": "same test-name example as touch",
    "heading": "same test-name example as touch",
    "health": "test_gdscript_signal_takes_the_event_mold and "
              "test_gdscript_private_variable_leading_underscore_blocks_suggesting_trailing "
              "in test_mutation_gate_vocabulary_check.py (added by #167)",
    "button": "no test requires this word canonical (the two tests that use it, "
              "test_on_prefix_is_exempt_via_the_core_convention_list and "
              "test_gdscript_autoconnect_handler_and_engine_virtuals_are_exempt in "
              "test_mutation_gate_vocabulary_check.py, exempt the whole `_on_...` name "
              "before any word is checked); kept as #167 landed it",
    "press": "same as button: no test requires it canonical, kept as #167 landed it",
    "viewer": "test_staged_tsx_component_passes_and_camel_case_function_blocks "
              "in test_mutation_gate_vocabulary_check.py (added by #167)",
}


def _mined_repo_counts() -> dict[str, int]:
    with MINING_TABLE.open("rb") as fh:
        table = tomllib.load(fh)
    return {row["text"]: row["repo_count"] for row in table["word"]}


def test_mining_table_pins_the_six_public_repos_by_sha():
    with MINING_TABLE.open("rb") as fh:
        table = tomllib.load(fh)
    shas = table["shas"]
    assert set(shas) == {
        "agent-sdlc", "ai-cpp-course", "flowdiff", "gst-nvmm-cpp", "standard", "strong-types",
    }
    assert all(len(sha) == 40 and all(c in "0123456789abcdef" for c in sha)
              for sha in shas.values())
    for row in table["word"]:
        assert set(row["occurrences"]) <= set(shas)
        assert row["repo_count"] == len(row["occurrences"])


def test_head_is_set_on_exactly_the_documented_agent_and_measurement_nouns():
    dictionary = vocabulary.load(REPO_ROOT, "")
    heads = {word for word, concept in dictionary.concepts.items() if concept.head}
    assert heads == {
        "count", "index", "viewer", "number", "size", "width", "ratio", "id",
        "server", "owner", "handler",
    }


def test_every_core_concept_meets_two_of_six_or_is_a_named_exception():
    dictionary = vocabulary.load(REPO_ROOT, "")
    counts = _mined_repo_counts()
    below_threshold = {word for word in dictionary.concepts if counts.get(word, 0) < 2}
    assert below_threshold == set(EXCEPTIONS)


def test_core_file_passes_the_no_leaks_scan():
    lines = CORE_PATH.read_text().splitlines()
    items = [(str(CORE_PATH), n, text) for n, text in enumerate(lines, start=1)]
    assert no_leaks._scan(items, []) == []


def test_curated_core_has_no_unresolved_wordnet_collision():
    dictionary = vocabulary.load(REPO_ROOT, "")
    words = tuple(dictionary.concepts)
    diff = vocabulary_wordnet.DictionaryDiff(
        source=str(CORE_PATH), added=words, changed=(), removed=()
    )
    try:
        collisions = vocabulary_wordnet._collisions_for(dictionary, [diff], {diff.source: ""})
    except GateError:
        pytest.skip("WordNet data not available offline in this environment")
    assert collisions == []
